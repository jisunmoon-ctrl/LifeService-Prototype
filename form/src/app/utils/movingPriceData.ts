// 유저 조건에 맞는 데이터 조회
export function findPriceData(
  이사유형: string,
  세부유형: string,
  출발지EV: string,
  목적지EV: string,
  인원수: string
): MovingPriceRow | undefined {
  return movingPriceData.find(
    (row) =>
      row.이사유형 === 이사유형 &&
      row.세부유형 === 세부유형 &&
      row.출발지EV === 출발지EV &&
      row.목적지EV === 목적지EV &&
      row.인원수 === 인원수
  );
}

// 동일 조건(EV, 인원수)에서 이사유형별 비교 데이터 조회
export function findPriceByMovingTypes(
  세부유형: string,
  출발지EV: string,
  목적지EV: string,
  인원수: string
): { 포장?: MovingPriceRow; 반포장?: MovingPriceRow; 일반?: MovingPriceRow } {
  const result: { 포장?: MovingPriceRow; 반포장?: MovingPriceRow; 일반?: MovingPriceRow } = {};

  for (const row of movingPriceData) {
    if (row.세부유형 === 세부유형 && row.출발지EV === 출발지EV && row.목적지EV === 목적지EV && row.인원수 === 인원수) {
      if (row.이사유형 === "포장") result.포장 = row;
      else if (row.이사유형 === "반포장") result.반포장 = row;
      else if (row.이사유형 === "일반") result.일반 = row;
    }
  }

  return result;
}

// 만원 단위로 포맷
export function formatWon(value: number): string {
  if (value >= 10000) {
    const man = Math.round(value / 10000);
    return `${man.toLocaleString()}만원`;
  }
  return `${value.toLocaleString()}원`;
}

// 원 단위 포맷 (콤마)
export function formatWonRaw(value: number): string {
  return `${value.toLocaleString()}원`;
}

// 이사유형+세부유형으로 모든 조건 조합 데이터 조회 (차트용)
export function findAllPriceDataByType(
  이사유형: string,
  세부유형: string
): MovingPriceRow[] {
  return movingPriceData.filter(
    (row) => row.이사유형 === 이사유형 && row.세부유형 === 세부유형
  );
}